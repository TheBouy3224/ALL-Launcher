package com.movtery.zalithlauncher.all.ui

import androidx.compose.runtime.Composable
import com.movtery.zalithlauncher.all.bridge.AllSubmitError
import com.movtery.zalithlauncher.all.bridge.AllToast

/** What the Desktop hands to every app window. */
class AllAppEnv(val showToast: (AllToast) -> Unit, val submitError: AllSubmitError)

/**
 * Registry of ALL "apps": self-contained windows that live on the Desktop (PHASE 4.0 foundation).
 *
 * An app is global (not tied to an instance): it gets a floating window, a taskbar chip, minimize/restore/Back handling
 * and, if [inStartMenu], a Start-menu entry, all generated by the Desktop from this list. Future tools (AI helper,
 * tutorial, Snake / easter eggs, Mod Doctor panel, ...) are added by appending one [AllApp] and nothing else.
 * Instance-level windows (Shaders / Screenshots / Servers / Worlds) keep using the Desktop's EXTRA_WINDOWS list for now.
 *
 * @param id stable id (also the window key)
 * @param emoji glyph used in title bar, taskbar chip and Start menu
 * @param titleRes string resource of the window title
 * @param iconRes drawable used in the Start menu (null = no icon)
 * @param content window content
 */
class AllApp(
    val id: String,
    val emoji: String,
    val titleRes: Int,
    val iconRes: Int? = null,
    val inStartMenu: Boolean = true,
    val content: @Composable (AllAppEnv) -> Unit
)

object AllAppRegistry {
    private val apps = mutableListOf<AllApp>()

    /** Registration is idempotent by id so recomposition / process restarts never duplicate an app. */
    fun register(app: AllApp) {
        if (apps.none { it.id == app.id }) apps += app
    }

    fun all(): List<AllApp> = apps.toList()
    fun find(id: String): AllApp? = apps.find { it.id == id }
}
